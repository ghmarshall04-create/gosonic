import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const sources = {
  "SonicBlastToken.sol": { content: readFileSync(resolve(root, "contracts/evm/src/SonicBlastToken.sol"), "utf8") },
  "SonicBlastFactory.sol": { content: readFileSync(resolve(root, "contracts/evm/src/SonicBlastFactory.sol"), "utf8") }
};
const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": {
        "*": ["abi", "evm.bytecode.object", "evm.methodIdentifiers"]
      }
    }
  }
};

const result = spawnSync("npx", ["--yes", "solc@0.8.34", "--standard-json"], {
  input: JSON.stringify(input),
  encoding: "utf8",
  cwd: root,
  maxBuffer: 16 * 1024 * 1024
});

if (result.error) throw result.error;
const outputStart = result.stdout.indexOf("{");
if (result.status !== 0 || outputStart < 0) {
  throw new Error(result.stderr || result.stdout || "Solidity compilation failed.");
}
const output = JSON.parse(result.stdout.slice(outputStart));
const errors = (output.errors || []).filter((entry) => entry.severity === "error");
if (errors.length) throw new Error(errors.map((entry) => entry.formattedMessage || entry.message).join("\n"));

const factory = output.contracts?.["SonicBlastFactory.sol"]?.SonicBlastFactory;
if (!factory?.evm?.bytecode?.object || !factory?.abi) throw new Error("Factory compiler artifact is incomplete.");

const artifact = {
  contractName: "SonicBlastFactory",
  compiler: "solc 0.8.34",
  source: "contracts/evm/src/SonicBlastFactory.sol",
  bytecode: `0x${factory.evm.bytecode.object}`,
  abi: factory.abi,
  methodIdentifiers: factory.evm.methodIdentifiers
};
const jsonTarget = resolve(root, "public/assets/sonicblast-factory-artifact.json");
const moduleTarget = resolve(root, "public/factory-artifact.js");
mkdirSync(dirname(jsonTarget), { recursive: true });
writeFileSync(jsonTarget, `${JSON.stringify(artifact, null, 2)}\n`);
writeFileSync(moduleTarget, `// Generated by scripts/build-factory-artifact.mjs. Do not edit by hand.\nexport const FACTORY_ARTIFACT = Object.freeze(${JSON.stringify(artifact, null, 2)});\n`);
console.log(`Wrote ${jsonTarget}`);
console.log(`Wrote ${moduleTarget}`);
